const IT_CATEGORIES = ['Ноутбук','Компьютер','Монитор','Принтер','Сканер','Телефон','Роутер','Сервер','Планшет']
const NON_IT_CATEGORIES = ['Холодильник','Морозильник','Весы','Стол','Стул','Шкаф','Кассовый аппарат','Кофемашина','Мебель','Витрина']

const mockAssets = []

// Helper to generate serials
let counter = 1000
function genSerial(prefix){
  counter += 1
  return `${prefix}-${counter}`
}

const sampleLocations = ['Двинцев','Спортмастер','АвтоВАЗ 1','Квартал','Сбербанк Оружейный','Марс Лужники']

// generate ~30 assets across sample locations
for(let i=0;i<30;i++){
  const isIt = Math.random() < 0.65
  const loc = sampleLocations[i % sampleLocations.length]
  const category = isIt ? IT_CATEGORIES[Math.floor(Math.random()*IT_CATEGORIES.length)] : NON_IT_CATEGORIES[Math.floor(Math.random()*NON_IT_CATEGORIES.length)]
  const model = category + ' Model ' + (Math.floor(Math.random()*200)+100)
  mockAssets.push({
    id: genSerial('SN'),
    serial: genSerial('SER'),
    category,
    model,
    quantity: Math.ceil(Math.random()*10),
    notes: Math.random() < 0.3 ? 'Требует ремонта' : '',
    location: loc
  })
}

